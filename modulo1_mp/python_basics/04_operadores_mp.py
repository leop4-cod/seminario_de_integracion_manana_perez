print ("Potencia")
print (costo_urna,"**",2, "=", costo_urna**2)
print ("Division")
print (costo_velacion,"/",costo_urna, "=", costo_velacion/costo_urna)
print ("Division Entera")
print (costo_velacion,"//",costo_urna, "=", costo_velacion//costo_urna)
print ("Módulo")
print (costo_velacion,"%",costo_urna, "=", costo_velacion%costo_urna)
